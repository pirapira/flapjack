def reals_rendering_mentions(declaration_source: str, names: set[str]) -> list[str]:
    """Rendering declarations used by a tagged declaration's own source text.

    The source is cut at the next attribute, docstring or section boundary so
    that a declaration without a body (for example a datatype) is not charged
    with the following declarations' text."""
    kept: list[str] = []
    for index, line in enumerate(declaration_source.splitlines()):
        if index > 0 and REALS_SOURCE_END_RE.match(line) and kept and not line.startswith("@[hol"):
            header_done = any(re.search(r"\b(?:def|theorem|lemma|abbrev|inductive|structure|instance|opaque)\b", k) for k in kept)
            if header_done:
                break
        kept.append(line)
    tokens = set(re.findall(r"[A-Za-z_][A-Za-z0-9_']*", strip_lean_comments("\n".join(kept))))
    return sorted(tokens & names)


def reals_as_rational_cuts_errors(declaration_source: str, qualified: bool,
                                  names: set[str]) -> list[str]:
    """`(reals_as_rational_cuts)` is required exactly when the declaration uses a
    reviewed binary64 real rendering in its own source.  Declarations that only
    refer to a qualified declaration inherit the assumption instead (recorded
    in the theorem map), and may not carry the qualifier themselves."""
    mentions = reals_rendering_mentions(declaration_source, names)
    if mentions and not qualified:
        return [
            "uses the binary64 real renderings "
            f"({', '.join(mentions[:4])}{', ...' if len(mentions) > 4 else ''}) and must carry "
            "(reals_as_rational_cuts)"
        ]
    if qualified and not mentions:
        return [
            "(reals_as_rational_cuts) is only for declarations whose own source uses a "
            "reviewed binary64 real rendering (Flapjack/Misc/MachineIeee.lean, "
            "Flapjack/Misc/BinaryIeee*.lean); dependents inherit the assumption instead"
        ]
    return []


def _qualified_word_owner_names(module: str, name: str, root: str) -> set[str]:
    """Read declaration namespaces, rather than infer them from file paths.

    A module can declare a carrier in a different namespace. Sections and
    mutual blocks delimit scopes but do not contribute identifier components.
    This is only source-name resolution; positivity and payload checks remain
    attached to the selected owning declaration.
    """
    info = _lean_file_info(module_source_file(module, Path(root)))
    if info is None:
        return set()
    namespace = ""
    scopes: list[str] = []
    names: set[str] = set()
    identifier = r"[A-Za-z_][A-Za-z0-9_']*(?:\.[A-Za-z_][A-Za-z0-9_']*)*"
    for line in strip_lean_comments(info.text).splitlines():
        command = line.strip()
        match = re.fullmatch(r"namespace\s+(" + identifier + r")", command)
        if match:
            scopes.append(namespace)
            suffix = match.group(1)
            if suffix.startswith("_root_."):
                namespace = suffix.removeprefix("_root_.")
            else:
                namespace = ".".join(part for part in (namespace, suffix) if part)
            continue
        if re.fullmatch(r"(?:noncomputable\s+)?section(?:\s+" + identifier + r")?|mutual", command):
            scopes.append(namespace)
            continue
        if re.fullmatch(r"end(?:\s+" + identifier + r")?", command):
            if scopes:
                namespace = scopes.pop()
            continue
        declaration = re.match(r"(?:structure|inductive)\s+(" + identifier + r")\b", command)
        if declaration and declaration.group(1).split(".")[-1] == name:
            declared = declaration.group(1)
            names.add(declared.removeprefix("_root_.") if declared.startswith("_root_.")
                      else ".".join(part for part in (namespace, declared) if part))
    return names


def predicate_quantified_carrier_scope(signature: str, body: str) -> str:
    """Types of explicit logical quantifier binders in a plain Prop definition.

    Unlike an abbreviation, a predicate's entire RHS is not a carrier scope:
    proof terms and discarded local values must not license a word qualifier.
    This deliberately narrow route handles direct logical predicates such as
    HOL wf_data; it does not infer types or inspect arbitrary helper bodies.
    """
    if (not re.match(r"\s*def\s", signature)
            or not re.search(r":\s*Prop\s*$", signature)
            or '"' in body
            or re.search(r"\b(?:let|have|by|fun|match)\b|:=|=>", body)):
        return ""
    carrier_types: list[str] = []
    for quantifier in re.finditer(r"[∀∃]\s*", body):
        start = quantifier.end()
        stack: list[str] = []
        closer = {"(": ")", "{": "}", "[": "]"}
        for end in range(start, len(body)):
            char = body[end]
            if char in closer:
                stack.append(char)
            elif char in (")", "}", "]"):
                if not stack or closer[stack.pop()] != char:
                    break
            elif char == "," and not stack:
                carrier_types.extend(
                    typ for typ in _binder_types(body[start:end])
                    if not _is_proof_premise_type(typ)
                )
                break
    return "\n".join(carrier_types)


WORD_PREDICATE_HEADER_RE = re.compile(
    r"^\s*def\s+([A-Za-z_][A-Za-z0-9_']*)\s*\(\s*([A-Za-z_][A-Za-z0-9_']*)\s*:\s*Nat\s*\)"
    r"\s*\[\s*NeZero\s+\2\s*\]"
)


def _module_word_predicates(lines: tuple[str, ...], module: str, root: str) -> list[str]:
    """Names of reviewed internally-word Prop predicates declared in a module.

    A predicate qualifies only when it carries `@[hol ...]` with
    `words_as_type_indexed_bitvec`, has the width-first `(w : Nat) [NeZero w]`
    header, and passes the plain-Prop internal quantifier route of
    docs/HOL-WORD-PREDICATES.md (checked with the full qualifier check).
    """
    found: list[str] = []
    for site in hol_attribute_sites(list(lines)):
        if not site[11]:
            continue
        source = strip_lean_comments(tagged_declaration_source(list(lines), site[0]))
        start = re.search(r"(?:^|\s)def\s", source)
        if start is None:
            continue
        declaration = source[start.start():].lstrip()
        if ":=" not in declaration:
            continue
        signature, body = declaration.split(":=", 1)
        header = WORD_PREDICATE_HEADER_RE.match(signature)
        if header is None or not predicate_quantified_carrier_scope(signature, body):
            continue
        if words_as_type_indexed_bitvec_errors(source, header.group(1), module, root, list(lines)):
            continue
        found.append(header.group(1))
    return found


@lru_cache(maxsize=None)
def reviewed_word_predicates(module: str, root: str) -> dict[str, tuple[str, ...]]:
    """Reviewed internally-word predicates visible from a module.

    The result maps each predicate name to the modules declaring it, so a
    same-named predicate in two modules is reported as ambiguous.
    """
    root_path = Path(root)
    current = _lean_file_info(module_source_file(module, root_path))
    if current is None:
        return {}
    result: dict[str, list[str]] = {}
    for name in _module_word_predicates(tuple(current.lines), module, root):
        result.setdefault(name, []).append(module)
    pending = list(current.imports)
    visited: set[str] = set()
    while pending:
        imported = pending.pop()
        if imported in visited:
            continue
        visited.add(imported)
        info = _lean_file_info(root_path / (imported.replace(".", "/") + ".lean"))
        if info is None:
            continue
        for name in _imported_module_word_predicates(imported, root):
            result.setdefault(name, []).append(imported)
        pending.extend(info.imports)
    return {name: tuple(owners) for name, owners in result.items()}


@lru_cache(maxsize=None)
def _imported_module_word_predicates(module: str, root: str) -> tuple[str, ...]:
    """Per-module cache of `_module_word_predicates` for an imported module."""
    info = _lean_file_info(Path(root) / (module.replace(".", "/") + ".lean"))
    if info is None:
        return ()
    if not any("words_as_type_indexed_bitvec" in line for line in info.lines):
        return ()
    return tuple(_module_word_predicates(tuple(info.lines), module, root))


def _signature_conclusion(signature: str) -> str:
    """Text after the last top-level `:` of a declaration signature."""
    depth = 0
    last = -1
    for index, char in enumerate(signature):
        if char in "([{⟨":
            depth += 1
        elif char in ")]}⟩":
            depth -= 1
        elif char == ":" and depth == 0:
            last = index
    return signature[last + 1:] if last >= 0 else ""


def word_predicate_application_errors(
    signature: str, module: str, root: str, lines: list[str]
) -> tuple[bool, list[str]]:
    """Accept a signature that applies a reviewed internally-word predicate.

    The predicate's words are internal to it (HOL `wf_data (:'a)`), so a
    theorem stated over it carries no word value of its own. The route
    applies only when every use of each referenced predicate is an
    application to an identifier bound in this signature as a `Nat` width
    with its own `[NeZero]` instance, at least one such application occurs in
    the conclusion, the predicate resolves to exactly one reviewed owner and
    no local declaration shadows it. See docs/HOL-WORD-PREDICATES.md.
    """
    # Equation-compiled theorems have no `:=`; their match arms are not part
    # of the statement.
    signature = re.split(r"\n\s*\|", signature, maxsplit=1)[0]
    predicates = reviewed_word_predicates(module, root)
    used = [name for name in predicates if identifier_token_occurs(signature, name)]
    if not used:
        return False, []
    errors: list[str] = []
    local_text = "\n".join(strip_lean_comments("\n".join(lines)).splitlines())
    conclusion = _signature_conclusion(signature)
    in_conclusion = False
    for name in used:
        owners = predicates[name]
        local_defs = len(re.findall(
            r"^\s*(?:private\s+|protected\s+|noncomputable\s+)*(?:def|abbrev|theorem|structure|inductive)\s+"
            + re.escape(name) + r"\b", local_text, re.M))
        local_reviewed = sum(1 for owner in owners if owner == module)
        if len(owners) != 1 or local_defs != local_reviewed:
            errors.append(f"words_as_type_indexed_bitvec predicate `{name}` must resolve to "
                          "a single reviewed internally-word predicate (no local shadow)")
            continue
        token = r"(?<![A-Za-z0-9_'.])" + re.escape(name) + r"(?![A-Za-z0-9_'])"
        uses = len(re.findall(token, signature))
        application = token + r"\s+(\(?[A-Za-z_][A-Za-z0-9_']*\)?|\(?\d+\)?)"
        widths = re.findall(application, signature)
        if len(widths) != uses:
            errors.append(f"words_as_type_indexed_bitvec predicate `{name}` must be applied "
                          "to its width at every use")
        binders = {match.group(1) for match in NAT_WIDTH_BINDER_RE.finditer(signature)}
        for width in widths:
            bare = width.strip("()")
            if bare.isdigit() or bare not in binders:
                errors.append(f"words_as_type_indexed_bitvec predicate `{name}` must be applied "
                              "to the signature's own Nat width, not a fixed or unbound dimension")
            else:
                errors.extend(word_dimension_errors(signature + "\nBitVec " + bare))
        if re.search(application, conclusion):
            in_conclusion = True
        # A premise use counts only under a named hypothesis binder; an
        # anonymous `(_ : P width x)` binder is a discarded use.
        for binder in re.finditer(r"[({]\s*([^\s:(){}]+)\s*:\s*([^(){}]*(?:\([^(){}]*\)[^(){}]*)*)[)}]",
                                  signature):
            if re.search(application, binder.group(2)) and not binder.group(1).startswith("_"):
                in_conclusion = in_conclusion or bool(conclusion.strip() and
                                                      conclusion.strip() != "True")
    if not in_conclusion:
        errors.append("words_as_type_indexed_bitvec predicate route requires an application "
                      "of the reviewed predicate in the conclusion or a named premise of a "
                      "non-trivial statement")
    return not errors, errors


def words_as_type_indexed_bitvec_errors(
    declaration_text: str,
    declaration: str,
    module: str = "",
    root: str = "",
    lines: list[str] | None = None,
) -> list[str]:
    """Validate the HOL word-dimension / FFI-universe translation qualifier.

    The qualifier records the candidate standard translation of HOL's
    type-indexed ``'a word`` (dimension ``dimindex (:α)``) to Lean's
    positive-width ``BitVec width`` and of HOL's ``'ffi ffi_state`` to a
    universe-0 Lean host type. It is a translation statement only: it changes
    no quantifier, hypothesis, side condition, or conclusion, and it requires
    no cross-assistant agreement theorem.

    The checker inspects EVERY word dimension named in the declaration scope,
    not only the first: each ``BitVec <id>`` (or reviewed abbreviation such as
    ``RiscV.Word <id>``) must sit at a bound ``Nat`` width parameter with its own
    ``[NeZero <id>]``. A literal zero dimension (``BitVec 0``) and a
    ``[NeZero 0]`` instance are rejected, so an unrelated ``[NeZero width]``
    cannot license a second, unconstrained word width. The ``[NeZero width]``
    discharge of ``dimindex (:α) ≥ 1`` must be retained and must not be
    restated as an extra hypothesis, and an FFI host type must be bound by a
    ``{σ : Type}``/``(σ : Type 0)`` binder at the universe-0 ``Type`` (a
    ``Type`` with a positive level, a universe-level variable, or ``Sort`` is
    rejected).

    A signature need not spell out ``BitVec`` when it is stated over a
    width-indexed carrier: the qualifier is also accepted when the signature
    names a structure or inductive family (declared locally or reached through
    imports) whose own header carries ``[NeZero <width>]`` and whose fields or
    constructor payloads reach a direct ``BitVec <width>`` field through
    uniquely resolved, HOL-tagged width-indexed carriers. Every owner in that
    chain must retain the same width and its own positivity instance. Resolution
    follows typed payload references, not names alone; a same-named local
    duplicate shadowing an imported owner is rejected as ambiguous. Existing
    special handling for HOL ``ValueHOL``/``HolWordLab`` additionally checks
    their exact one-constructor wrapper shape.

    A plain ``def`` returning ``Prop`` may instead quantify word values
    internally. Only explicit logical quantifier binder types contribute to
    this scope; discarded local terms and proof bodies do not. Each internal
    dimension must still be discharged by the predicate's own signature.
    See docs/HOL-WORD-PREDICATES.md for this deliberately narrow contract.
    """
    errors: list[str] = []
    if not declaration_text.strip():
        return [
            "words_as_type_indexed_bitvec requires a resolvable tagged declaration "
            f"signature (checked for `{declaration}`)"
        ]
    stripped = strip_lean_comments(declaration_text)
    decl_start = re.search(
        r"(?:^|\s)(?:def|theorem|lemma|abbrev|instance|structure)\s", stripped
    )
    if decl_start is not None:
        stripped = stripped[decl_start.start():]
    has_body = ":=" in stripped
    signature, body = stripped.split(":=", 1) if has_body else (stripped, "")
    if not signature.strip():
        signature = stripped
    # For a type abbreviation, the words occur in its RHS, while Lean's
    # elaborated declaration type is only `Nat → Type`. Check the body for
    # carriers and the signature for the matching Nat/[NeZero] binders.
    predicate_scope = predicate_quantified_carrier_scope(signature, body)
    if re.search(r"\babbrev\s", signature):
        word_scope = signature + "\n" + body
    else:
        word_scope = signature + "\n" + predicate_scope

    # Internal quantifiers cannot supply a replacement width binder or a
    # nested positivity instance: their word dimensions belong to the tagged
    # predicate's own signature, just as for a signature-level word value.
    if predicate_scope:
        errors.extend(word_dimension_errors(signature + "\n" + predicate_scope))
        if lines is not None and module and root:
            internal_headers = structure_headers(lines)
            internal_headers.update(inductive_headers(lines))
            imported_headers: dict[str, list[str]] = {}
            for owners in (imported_structure_owners(module, root),
                           imported_inductive_owners(module, root)):
                for name, entries in owners.items():
                    imported_headers.setdefault(name, []).extend(header for _, header, _ in entries)
            for name, header in internal_headers.items():
                imported_headers.setdefault(name, []).append(header)
            for name, headers in imported_headers.items():
                for header in headers:
                    # The reviewed width-first carrier convention. Other
                    # carrier application forms remain outside this route.
                    if not re.match(r"\s*[({]\s*[^:(){}]+\s*:\s*Nat\s*[)}]", header):
                        continue
                    for width in re.findall(r"(?<![A-Za-z0-9_'])" + re.escape(name)
                                            + r"\s+(\(?[A-Za-z_][A-Za-z0-9_']*\)?|\(?\d+\)?)",
                                            predicate_scope):
                        if width.strip("()").isdigit():
                            errors.append("words_as_type_indexed_bitvec internal carrier "
                                          "requires its predicate signature's Nat width, "
                                          "not a fixed literal dimension")
                        errors.extend(word_dimension_errors(signature + "\nBitVec " + width))

    errors.extend(word_dimension_errors(word_scope))
    direct_ids = set(word_dimension_identifier_atoms(word_scope))
    # A literal dimension such as `BitVec 5` (the `5 word` globals key type, say)
    # is not itself the `dimindex (:α)` translation; only an identifier dimension
    # takes the direct route. A literal-only signature still has to resolve a
    # reviewed carrier, and a literal `0` is rejected by `word_dimension_errors`.
    has_direct_word = bool(direct_ids)
    if has_direct_word:
        direct_widths = set(
            match.group(1) for match in NAT_WIDTH_BINDER_RE.finditer(signature)
        )
        if not any(identifier in direct_widths for identifier in direct_ids):
            errors.append(
                "words_as_type_indexed_bitvec must name the Lean positive-width word "
                "carrier `BitVec <width>` at a `Nat` width binder that translates HOL "
                "`'a word`; a fixed literal dimension is not the `dimindex (:α)` "
                "translation"
            )

    carrier_ok = bool(module and root and reviewed_hol_prog_word_alias(signature, module, root))
    # Only the approved gc predicates inherit the reviewed function alias
    # translation. Keep arbitrary higher-order aliases outside this route.
    if (not carrier_ok and module and root and lines is not None
            and gc_function_predicate_signature(signature + " := True", declaration)):
        sites = [site for site in hol_attribute_sites(lines, include_fmap_function=True)
                 if tuple(site[1:3]) in GC_FUNCTION_PREDICATE_REFERENCES
                 and site[11] and site[-1] == ("argument_4", "result_3")
                 and gc_function_predicate_signature(
                     tagged_declaration_source(lines, site[0]), declaration)]
        carrier_ok = bool(len(sites) == 1 and reviewed_gc_function_alias(module, root))
    pending_predicate_errors: list[str] = []
    # A theorem stated over a reviewed internally-word predicate (HOL
    # `wf_data (:'a)`) inherits that predicate's word scope, under the narrow
    # application rules of `word_predicate_application_errors`.
    if (not has_direct_word and not carrier_ok and not predicate_scope
            and module and root and lines is not None
            and not re.search(r"\babbrev\s", signature)):
        predicate_ok, pending_predicate_errors = word_predicate_application_errors(
            signature, module, root, lines)
        carrier_ok = predicate_ok
    if identifier_token_occurs(signature, "HolProg") and not carrier_ok:
        errors.append("words_as_type_indexed_bitvec requires the source-resolved canonical "
                      "HolProg alias, its unique word payload owners and each positive width")
    if not has_direct_word and not carrier_ok and lines is not None and module and root:
        local_types = structure_field_types(lines)
        local_types.update(inductive_constructor_types(lines))
        local_headers = structure_headers(lines)
        local_headers.update(inductive_headers(lines))
        imported_owners = {
            name: list(owners)
            for name, owners in imported_structure_owners(module, root).items()
        }
        for name, owners in imported_inductive_owners(module, root).items():
            imported_owners.setdefault(name, []).extend(owners)
        all_owners_by_name: dict[str, list[tuple[str, str, dict[str, str]]]] = {}
        for name in set(local_types) | set(imported_owners):
            owners: list[tuple[str, str, dict[str, str]]] = []
            if name in local_types:
                owners.append(
                    (module, local_headers.get(name, ""), local_types[name])
                )
            owners.extend(imported_owners.get(name, []))
            all_owners_by_name[name] = owners
        owners_by_name = {
            name: owners for name, owners in all_owners_by_name.items()
            if identifier_token_occurs(word_scope, name)
        }
        signature_names = set(re.findall(
            r"[A-Za-z_][A-Za-z0-9_']*(?:\.[A-Za-z_][A-Za-z0-9_']*)*", word_scope
        ))
        for name, owners in list(owners_by_name.items()):
            # A bare occurrence remains ambiguous, including a local shadow.
            # Only an actual qualified declaration name can select one owner;
            # never pool positivity or word fields across different owners.
            if len(owners) > 1 and name not in signature_names:
                selected = [owner for owner in owners
                            if _qualified_word_owner_names(owner[0], name, root)
                            & signature_names]
                if len(selected) == 1:
                    owners_by_name[name] = selected
                    all_owners_by_name[name] = selected
        ambiguous = [
            name for name, owners in owners_by_name.items() if len(owners) != 1
        ]
        if ambiguous:
            errors.append(
                "words_as_type_indexed_bitvec must resolve each width-indexed "
                "carrier to a single owning declaration; ambiguous same-named "
                "owners were found for "
                + ", ".join(sorted(ambiguous))
                + " (a local duplicate shadowing an imported owner must be "
                "removed or disambiguated by signature)"
            )
        else:
            candidate_errors: list[str] = []
            def has_hol_tag(owner_module: str, owner_name: str) -> bool:
                info = _lean_file_info(module_source_file(owner_module, Path(root)))
                if info is None:
                    return False
                source_lines = info.parsed(
                    "stripped_lines",
                    lambda i: strip_lean_comments(i.text).splitlines(),
                )
                inductive_re = re.compile(
                    rf"^\s*inductive\s+{re.escape(owner_name)}(?:\s|\()"
                )
                declaration_line = next(
                    (
                        index for index, line in enumerate(source_lines)
                        if inductive_re.match(line)
                    ),
                    None,
                )
                if declaration_line is None:
                    return False
                # Allow a multiline @[hol] attribute, but do not borrow one
                # from an earlier declaration in the same module.
                prefix: list[str] = []
                declaration_re = re.compile(
                    r"^\s*(?:def|theorem|lemma|abbrev|instance|structure|inductive)\s"
                )
                for line in reversed(source_lines[:declaration_line]):
                    if declaration_re.match(line):
                        break
                    prefix.append(line)
                return any("@[hol" in line for line in prefix)

            def owner_has_width(
                owner: tuple[str, str, dict[str, str]], width: str
            ) -> bool:
                _owner_module, header, _payloads = owner
                return (
                    re.search(
                        r"[\{\(]\s*" + re.escape(width) + r"\s*:\s*Nat\s*[\}\)]",
                        header,
                    ) is not None
                    and re.search(
                        r"\[\s*NeZero\s+" + re.escape(width) + r"\s*\]",
                        header,
                    ) is not None
                )

            def reaches_bitvec(owner_name: str, width: str, seen: set[str]) -> bool:
                if owner_name in seen:
                    return False
                owners = all_owners_by_name.get(owner_name, [])
                if len(owners) != 1:
                    return False
                owner_module, header, payloads = owners[0]
                if not owner_has_width(owners[0], width):
                    return False
                # This recursive path is for exact syntax families only. It
                # must not accept an unrelated aggregate that merely contains
                # a word-bearing field.
                if not has_hol_tag(owner_module, owner_name):
                    return False
                owner_text = header + "\n" + "\n".join(payloads.values())
                dimension_ids = set(word_dimension_identifier_atoms(owner_text))
                if word_dimension_errors(owner_text):
                    return False
                if dimension_ids:
                    return width in dimension_ids and dimension_ids <= {width}
                next_seen = seen | {owner_name}
                payload_text = "\n".join(payloads.values())
                for nested_name, nested_owners in all_owners_by_name.items():
                    if len(nested_owners) != 1 or nested_name in next_seen:
                        continue
                    if not has_hol_tag(nested_owners[0][0], nested_name):
                        continue
                    if not owner_has_width(nested_owners[0], width):
                        continue
                    if re.search(
                        rf"(?<![A-Za-z0-9_']){re.escape(nested_name)}\s+"
                        rf"\(?{re.escape(width)}\)?(?![A-Za-z0-9_'])",
                        payload_text,
                    ) and reaches_bitvec(nested_name, width, next_seen):
                        return True
                return False

            def exact_hol_word_lab_carrier() -> bool:
                # ValueHOL stores word values through the exact HOL `word_lab`
                # wrapper. Do not bless HolWordLab by its name: resolve its
                # unique declaration and check its positive width and sole
                # BitVec payload before accepting the aggregate ValueHOL.
                nested_owners: list[tuple[str, str, dict[str, str]]] = []
                if "HolWordLab" in local_types:
                    nested_owners.append((
                        module, local_headers.get("HolWordLab", ""),
                        local_types["HolWordLab"],
                    ))
                nested_owners.extend(imported_owners.get("HolWordLab", []))
                if len(nested_owners) != 1:
                    return False
                _nested_module, nested_header, nested_payloads = nested_owners[0]
                nested_text = nested_header + "\n" + "\n".join(
                    nested_payloads.values()
                )
                nested_ids = word_dimension_identifier_atoms(nested_text)
                nested_widths = {
                    match.group(1) for match in NAT_WIDTH_BINDER_RE.finditer(nested_header)
                }
                if (
                    word_dimension_errors(nested_text)
                    or len(nested_ids) != 1
                    or nested_ids[0] not in nested_widths
                    or len(nested_payloads) != 1
                ):
                    return False
                payload = next(iter(nested_payloads.values()))
                fields = re.findall(
                    r"\(\s*[A-Za-z_][A-Za-z0-9_']*\s*:\s*([^()]+?)\s*\)",
                    payload,
                )
                return fields == [f"BitVec {nested_ids[0]}"]

            for owner_name, owners in owners_by_name.items():
                _owner_module, header, fields = owners[0]
                owner_text = header + "\n" + "\n".join(fields.values())
                owner_errors = word_dimension_errors(owner_text)
                owner_ids = set(word_dimension_identifier_atoms(owner_text))
                owner_widths = set(
                    match.group(1) for match in NAT_WIDTH_BINDER_RE.finditer(owner_text)
                )
                if (
                    not owner_errors
                    and any(identifier in owner_widths for identifier in owner_ids)
                ):
                    carrier_ok = True
                    break
                # Exact HOL `panSem$v` (`ValueHOL`) contains `HolWordLab width`
                # in its Val constructor. Resolve both owners independently:
                # ValueHOL must retain positive width, and HolWordLab must be
                # its exact one-constructor BitVec wrapper at positive width.
                if owner_name == "ValueHOL":
                    value_text = owner_text.replace("HolWordLab", "BitVec")
                    value_ids = word_dimension_identifier_atoms(value_text)
                    value_widths = {
                        match.group(1)
                        for match in NAT_WIDTH_BINDER_RE.finditer(header)
                    }
                    if (
                        not word_dimension_errors(value_text)
                        and value_ids
                        and all(identifier in value_widths for identifier in value_ids)
                        and exact_hol_word_lab_carrier()
                    ):
                        carrier_ok = True
                        break
                # Some exact HOL syntax is several datatypes away from words
                # at the theorem boundary (DeclHOL -> FunDeclHOL -> ProgHOL ->
                # ExpHOL -> BitVec). Follow only typed payload references
                # through unique, tagged owners, preserving the same width.
                owner_widths = {
                    match.group(1)
                    for match in NAT_WIDTH_BINDER_RE.finditer(header)
                }
                if len(owner_widths) == 1:
                    width = next(iter(owner_widths))
                    if (
                        owner_has_width(owners[0], width)
                        and has_hol_tag(_owner_module, owner_name)
                        and reaches_bitvec(owner_name, width, set())
                    ):
                        carrier_ok = True
                        break
                if owner_ids and not candidate_errors:
                    candidate_errors = owner_errors
            if not carrier_ok and candidate_errors:
                errors.extend(candidate_errors)

    if not has_direct_word:
        if not carrier_ok:
            # Reported only when no other carrier route qualifies.
            errors.extend(pending_predicate_errors)
            errors.append(
                "words_as_type_indexed_bitvec must name the Lean positive-width word "
                "carrier `BitVec` that translates HOL `'a word`, or name a reviewed "
                "width-indexed carrier structure whose fields include `BitVec`-typed "
                "fields and whose declaration retains `[NeZero width]`"
            )
        if "NeZero" not in signature and not carrier_ok:
            errors.append(
                "words_as_type_indexed_bitvec must retain the `[NeZero width]` discharge "
                "of HOL `dimindex (:α) ≥ 1`"
            )
    extra = WORD_POSITIVITY_EXTRA_RE.search(signature)
    if extra is not None:
        errors.append(
            "words_as_type_indexed_bitvec must not restate word-dimension positivity "
            f"as an extra hypothesis (`{extra.group(0).strip()}`); `[NeZero width]` is "
            "the only allowed side condition"
        )
    if HOL_FFI_CARRIER_RE.search(signature):
        host_binder = re.search(
            r"[\{\(]\s*[^\s:(){}]+\s*:\s*Type\s*0?\s*[\}\)]", signature
        )
        if host_binder is None:
            errors.append(
                "words_as_type_indexed_bitvec must bind the FFI host type at a `Type` "
                "universe for HOL `'ffi ffi_state`"
            )
        if (
            FFI_UNIVERSE_LEVEL_RE.search(signature) is not None
            or FFI_SORT_RE.search(signature) is not None
            or re.search(r":\s*Type\s+(?!0\b)\d", signature) is not None
        ):
            errors.append(
                "words_as_type_indexed_bitvec must not introduce an FFI universe-level "
                "variable or a `Sort`; use the universe-0 `Type` instance"
            )
    return errors


def word_dimension_as_width_errors(declaration_text: str, declaration: str,
                                   width_name: str) -> list[str]:
    """Validate the narrow word-free type-dimension-to-Nat translation."""
    if not declaration_text.strip():
        return [
            "word_dimension_as_width requires a resolvable tagged declaration "
            f"signature (checked for `{declaration}`)"
        ]
    stripped = strip_lean_comments(declaration_text)
    decl_start = re.search(
        r"(?:^|\s)(?:def|theorem|lemma|abbrev|instance|structure)\s", stripped
    )
    if decl_start is not None:
        stripped = stripped[decl_start.start():]
    signature = stripped.split(":=", 1)[0]
    if not signature.strip():
        signature = stripped
    widths = {match.group(1) for match in NAT_WIDTH_BINDER_RE.finditer(signature)}
    errors: list[str] = []
    if width_name not in widths:
        errors.append(
            f"word_dimension_as_width `{width_name}` must name an explicit `(width : Nat)` binder"
        )
    if re.search(
        r"\[\s*NeZero\s+" + re.escape(width_name) + r"\s*\]", signature
    ) is None:
        errors.append(
            f"word_dimension_as_width `{width_name}` must retain its own `[NeZero {width_name}]` binder"
        )
    if WORD_CARRIER_TOKEN_RE.search(signature):
        errors.append(
            "word_dimension_as_width is only for word-free signatures; use "
            "words_as_type_indexed_bitvec for a signature carrying words"
        )
    return errors

# HOL's terminating eval_def generates eval_ind; the complete source block is
# reviewed against the closed original kernel capture in the faithful expression
# probes. This bounded recognition records provenance, not Lean/HOL equivalence.
PANSEM_EVAL_IND_PATH = "cakeml/pancake/semantics/panSemScript.sml"
PANSEM_EVAL_DEF_SHA256 = "21a7f3b7c750de70e880511098d0317098d3486515d226bdad734f651a61a715"


def pansem_eval_ind_declaration(path: Path, source: str) -> int | None:
    if path.parts[-4:] != tuple(PANSEM_EVAL_IND_PATH.split("/")):
        return None
    blocks = list(re.finditer(r"^Definition eval_def:\n.*?^End\b", source, re.M | re.S))
    if len(blocks) != 1:
        return None
    block = blocks[0]
    if hashlib.sha256(block.group().encode()).hexdigest() != PANSEM_EVAL_DEF_SHA256:
        return None
    return source.count("\n", 0, block.start()) + 1


def hol_declaration_lines(
    path: Path, cache: dict[Path, dict[str, list[int]]]
) -> dict[str, list[int]]:
    if path not in cache:
        names: dict[str, list[int]] = {}
        header = re.compile(
            r"^(?:%s)\s+([A-Za-z0-9_']+)" % "|".join(HOL_HEADER_KEYWORDS)
        )
        sml_val = re.compile(r"^val\s+([A-Za-z0-9_']+)\s*=")
        # HOL ``Datatype:`` blocks put the declared type name on the next
        # line(s) (``name = ...``) and terminate with a top-level ``End``.  A
        # type name may also sit on its own line with the ``=`` beginning the
        # following line (for example ``shmem_info_num``), so a bare name is
        # remembered and indexed once its ``=`` line is seen.  The one-line
        # header form ``Datatype: name = ...`` (for example binary_ieee's
        # ``float_value`` and ``float_compare``) declares ``name`` on the
        # header line itself and still ends with ``End``.
        datatype_header = re.compile(r"^Datatype\s*:?\s*$")
        datatype_inline = re.compile(r"^Datatype\s*:\s*([A-Za-z0-9_']+)\s*=")
        datatype_name = re.compile(r"^\s*([A-Za-z0-9_']+)\s*=")
        datatype_bare_name = re.compile(r"^\s*([A-Za-z0-9_']+)\s*$")
        datatype_equals = re.compile(r"^\s*=")
        datatype_end = re.compile(r"^End\b")
        in_datatype = False
        pending_datatype_name: tuple[str, int] | None = None
        with path.open(encoding="utf-8", errors="replace") as handle:
            for number, line in enumerate(handle, start=1):
                if in_datatype:
                    if datatype_end.match(line):
                        in_datatype = False
                        pending_datatype_name = None
                    else:
                        match = datatype_name.match(line)
                        if match:
                            names.setdefault(match.group(1), []).append(number)
                            pending_datatype_name = None
                        elif (
                            pending_datatype_name is not None
                            and datatype_equals.match(line)
                        ):
                            name, name_line = pending_datatype_name
                            names.setdefault(name, []).append(name_line)
                            pending_datatype_name = None
                        else:
                            bare = datatype_bare_name.match(line)
                            if bare:
                                pending_datatype_name = (bare.group(1), number)
                    continue
                if datatype_header.match(line):
                    in_datatype = True
                    continue
                inline = datatype_inline.match(line)
                if inline:
                    names.setdefault(inline.group(1), []).append(number)
                    in_datatype = True
                    continue
                match = header.match(line) or sml_val.match(line)
                if match:
                    names.setdefault(match.group(1), []).append(number)
        for generated, number, _end in HOL_RELN_TUPLES(
            path.read_text(encoding="utf-8", errors="replace")
        ):
            for name in generated:
                names.setdefault(name, []).append(number)
        for carrier, _runner, number, _end in HOL_DEFINE_RUN(
            path.read_text(encoding="utf-8", errors="replace")
        ):
            names.setdefault(carrier, []).append(number)
        source_text = path.read_text(encoding="utf-8", errors="replace")
        eval_ind_line = pansem_eval_ind_declaration(path, source_text)
        if eval_ind_line is not None:
            names.setdefault("eval_ind", []).append(eval_ind_line)
        # `val NAME = fetch "-" "NAME";` re-binds the theorem the factory
        # generated under its own name; it is the same declaration, already
        # recorded at the alias line, so the factory line is not a second one.
        fetch_aliases = set(re.findall(
            r'^val\s+([A-Za-z0-9_\']+)\s*=\s*fetch\s+"-"\s+"\1"\s*;',
            source_text, re.MULTILINE))
        for generated, number, _end in (HOL_MONAD_ACCESSORS(source_text) +
                                        HOL_MONAD_EXCEPTIONS(source_text) +
                                        HOL_L3_TYPES(source_text)):
            for name in generated:
                if name in fetch_aliases:
                    continue
                names.setdefault(name, []).append(number)
        if path.parts[-4:] == tuple(MACHINE_IEEE_SCRIPT.split("/")):
            if machine_ieee_fp64_source_error(path.parents[3]) is None:
                for name in MACHINE_IEEE_FP64_NAMES:
                    names.setdefault(name, []).append(MACHINE_IEEE_FP64_LINE)
            if machine_ieee_fp32_source_error(path.parents[3]) is None:
                for name in MACHINE_IEEE_FP32_NAMES:
                    names.setdefault(name, []).append(MACHINE_IEEE_FP32_LINE)
        if path.parts[-len(Path(L3_BOOLIFY_SCRIPT).parts):] == Path(L3_BOOLIFY_SCRIPT).parts:
            root = path.parents[len(Path(L3_BOOLIFY_SCRIPT).parts) - 1]
            if l3_boolify_source_error(root) is None:
                for name, (_width, line) in L3_BOOLIFY_DECLARATIONS.items():
                    names.setdefault(name, []).append(line)
        for locations in names.values():
            locations.sort()
        cache[path] = names
    return cache[path]


def hol_ref_error(
    path: Path, name: str, line: int | None,
    cache: dict[Path, dict[str, list[int]]]
) -> str | None:
    if (path.parts[-4:] == tuple(MACHINE_IEEE_SCRIPT.split("/"))
            and name in MACHINE_IEEE_FP64_NAMES):
        error = machine_ieee_fp64_source_error(path.parents[3])
        if error:
            return error
        if line != MACHINE_IEEE_FP64_LINE:
            return (f"generated `{name}` requires the literal fp64 factory call "
                    f"source line {MACHINE_IEEE_FP64_LINE} in @[hol]")
    if (path.parts[-4:] == tuple(MACHINE_IEEE_SCRIPT.split("/"))
            and name in MACHINE_IEEE_FP32_NAMES):
        error = machine_ieee_fp32_source_error(path.parents[3])
        if error:
            return error
        if line != MACHINE_IEEE_FP32_LINE:
            return (f"generated `{name}` requires the literal fp32 factory call "
                    f"source line {MACHINE_IEEE_FP32_LINE} in @[hol]")
    declared = hol_declaration_lines(path, cache).get(name, [])
    if not declared:
        return f"declares no `{name}`"
    if line is None and len(declared) > 1:
        return (
            f"declares `{name}` at multiple lines {declared}; "
            "add the source line to @[hol]"
        )
    if line is not None and line not in declared:
        return f"declares `{name}` at {declared}, not at line {line}"
    return None


def main(argv: list[str]) -> int:
    want_mapping = "--mapping" in argv
    want_orphans = "--orphans" in argv
    errors: list[str] = []
    mapping: list[tuple[str, str, str, str]] = []
    cache: dict[Path, dict[str, list[int]]] = {}
    reachable = reachable_modules()

    if not (ROOT / "cakeml" / "pancake").is_dir():
        print(
            "error: the cakeml submodule is not checked out; run "
            "`git submodule update --init --depth 1 -- cakeml`",
            file=sys.stderr,
        )
        return 1

    observation_manifest = ROOT / "docs/HOL-THEOREM-MAP.json"
    observation_records = json.loads(observation_manifest.read_text()) if observation_manifest.is_file() else []
    reals_names = reals_rendering_names(ROOT)
    for lean_path in lean_files():
        rel = lean_path.relative_to(ROOT).as_posix()
        lines = lean_path.read_text(encoding="utf-8").splitlines()
        module = module_name(lean_path)
        module_reported = False
        for (number, hol_path, hol_name, hol_line, list_fields,
             names_fields, boundary_fields, fmap_fields, fmap_result,
             fmap_relation, fmap_equalities, words_bitvec,
             fmap_parameters, fmap_existentials, dimension_width,
             fmap_function_positions, fmap_heterogeneous_function_positions, reals_cuts,
             fmap_equality, result_observations) in hol_attribute_sites(
                lines, include_fmap_existentials=True,
                include_word_dimension_width=True,
                include_fmap_function=True,
                include_fmap_heterogeneous_function=True,
                include_reals_as_rational_cuts=True,
                include_fmap_as_finite_support_equality=True,
                include_result_observations=True,
             ):
            where = f"{rel}:{number}"
            if result_observations:
                if (list_fields or names_fields or fmap_fields or fmap_result or fmap_relation or
                    fmap_equalities or words_bitvec or fmap_parameters or fmap_existentials or
                    dimension_width or fmap_function_positions or fmap_heterogeneous_function_positions or
                    reals_cuts or fmap_equality):
                    errors.append(f"{where}: result observations cannot combine with other representation qualifiers")
                errors.extend(f"{where}: {error}" for error in fmap_result_observation_errors(
                    lines, module, tagged_declaration_text(lines, number),
                    result_observations, observation_records))
            errors.extend(
                f"{where}: {error}"
                for error in reals_as_rational_cuts_errors(
                    tagged_declaration_source(lines, number), reals_cuts, reals_names,
                )
            )
            lean_decl = find_lean_decl(lines, number - 1)
            if module not in reachable and not module_reported:
                module_reported = True
                errors.append(
                    f"{rel}: module {module} carries @[hol] but is not imported "
                    f"(transitively) from Flapjack.lean, so `lake build Flapjack` "
                    f"never checks it; add the import to Flapjack.lean"
                )
            if list_fields:
                errors.extend(
                    f"{where}: {error}"
                    for error in list_as_array_errors(lines, list_fields, rel)
                )
            if fmap_fields:
                errors.extend(
                    f"{where}: {error}"
                    for error in fmap_as_finite_support_errors(
                        lines, fmap_fields, rel, tagged_declaration_text(lines, number)
                    )
                )
            if fmap_parameters:
                if fmap_fields or fmap_result or fmap_relation or fmap_equalities:
                    errors.append(
                        f"{where}: fmap_as_finite_support_parameters is "
                        "mutually exclusive with other finite-map qualifiers"
                    )
                errors.extend(
                    f"{where}: {error}"
                    for error in fmap_as_finite_support_parameters_errors(
                        lines, rel, tagged_declaration_text(lines, number),
                        lean_decl, fmap_parameters,
                    )
                )
            if fmap_existentials:
                errors.extend(
                    f"{where}: {error}"
                    for error in fmap_as_finite_support_existentials_errors(
                        lines, module, tagged_declaration_source(lines, number),
                        lean_decl, fmap_existentials,
                    )
                )
            if fmap_result:
                errors.extend(
                    f"{where}: {error}"
                    for error in fmap_as_finite_support_result_errors(
                        lines, rel, tagged_declaration_text(lines, number), lean_decl
                    )
                )
            if fmap_function_positions:
                errors.extend(
                    f"{where}: {error}"
                    for error in fmap_as_finite_support_function_errors(
                        lines, tagged_declaration_source(lines, number), lean_decl,
                        fmap_function_positions, module=module, root=str(ROOT),
                        hol_reference=(hol_path, hol_name),
                        words_bitvec=words_bitvec,
                    )
                )
                if (fmap_fields or fmap_result or fmap_parameters or fmap_existentials
                        or fmap_relation or fmap_equalities):
                    errors.append(
                        f"{where}: fmap_as_finite_support_function is mutually "
                        "exclusive with other finite-map qualifiers"
                    )
            if fmap_heterogeneous_function_positions:
                if (fmap_fields or fmap_result or fmap_parameters or fmap_existentials
                        or fmap_relation or fmap_equalities or fmap_function_positions):
                    errors.append(
                        f"{where}: fmap_as_finite_support_heterogeneous_function is mutually "
                        "exclusive with other finite-map qualifiers"
                    )
                errors.extend(
                    f"{where}: {error}"
                    for error in fmap_as_finite_support_heterogeneous_function_errors(
                        lines, tagged_declaration_source(lines, number), lean_decl,
                        fmap_heterogeneous_function_positions,
                    )
                )
            if fmap_relation:
                errors.extend(
                    f"{where}: {error}"
                    for error in fmap_as_finite_support_relation_errors(
                        lines, fmap_relation, rel, tagged_declaration_text(lines, number)
                    )
                )
            if fmap_equalities:
                errors.extend(
                    f"{where}: {error}"
                    for error in fmap_as_finite_support_equalities_errors(
                        lines, rel, tagged_declaration_text(lines, number), lean_decl
                    )
                )
            if fmap_equality:
                if (fmap_fields or fmap_result or fmap_parameters or fmap_existentials
                        or fmap_relation or fmap_equalities or fmap_function_positions
                        or fmap_heterogeneous_function_positions):
                    errors.append(
                        f"{where}: fmap_as_finite_support_equality is mutually "
                        "exclusive with other finite-map qualifiers"
                    )
                errors.extend(
                    f"{where}: {error}"
                    for error in fmap_as_finite_support_equality_errors(
                        lines, rel, tagged_declaration_text(lines, number), lean_decl
                    )
                )
            if names_fields or boundary_fields:
                errors.extend(
                    f"{where}: {error}"
                    for error in names_as_string_errors(
                        lines, names_fields, boundary_fields, rel, lean_decl
                    )
                )
            if words_bitvec:
                errors.extend(
                    f"{where}: {error}"
                    for error in words_as_type_indexed_bitvec_errors(
                        tagged_declaration_source(lines, number),
                        lean_decl,
                        module=module,
                        root=str(ROOT),
                        lines=lines,
                    )
                )
            if dimension_width:
                if words_bitvec:
                    errors.append(
                        f"{where}: word_dimension_as_width is mutually exclusive with "
                        "words_as_type_indexed_bitvec"
                    )
                errors.extend(
                    f"{where}: {error}"
                    for error in word_dimension_as_width_errors(
                        tagged_declaration_text(lines, number), lean_decl,
                        dimension_width,
                    )
                )
            target = ROOT / hol_path
            source_error = hol_source_error(ROOT, hol_path)
            if source_error is not None:
                errors.append(f"{where}: {source_error}: {hol_path}")
                continue
            if not target.is_file():
                errors.append(f"{where}: HOL file does not exist: {hol_path}")
                continue
            ref_error = hol_ref_error(target, hol_name, hol_line, cache)
            if ref_error is not None:
                errors.append(
                    f"{where}: {hol_path} {ref_error} "
                    f"(cited by {lean_decl})"
                )
                continue
            mapped_name = f"{hol_name}:{hol_line}" if hol_line is not None else hol_name
            mapping.append((where, lean_decl, hol_path, mapped_name))

    if want_mapping:
        for row in mapping:
            print("\t".join(row))

    if want_orphans:
        orphans = sorted(
            module_name(path)
            for path in lean_files()
            if path.is_relative_to(ROOT / "Flapjack")
            and not path.is_relative_to(ROOT / "Flapjack" / "Test")
            and module_name(path) not in reachable
        )
        for module in orphans:
            print(f"warning: {module} is not reachable from Flapjack.lean", file=sys.stderr)

    if errors:
        for error in errors:
            print(f"error: {error}", file=sys.stderr)
        print(f"{len(errors)} bad @[hol] reference(s)", file=sys.stderr)
        return 1
    print(f"{len(mapping)} @[hol] reference(s) checked", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
