def fmap_as_finite_support_function_errors(
    lines: list[str], declaration_source: str, decl_name: str,
    positions: tuple[str, ...], *, module: str = "", root: str = "",
    hol_reference: tuple[str, str] | None = None,
    words_bitvec: bool = False,
) -> list[str]:
    """Validate the exact nested finite-map slots of a function type alias.

    Normally this qualifier requires a type abbreviation with one top-level
    arrow, a tuple argument, and an Option-wrapped tuple result. The sole
    approved predicate extensions are original wordProps gc_fun_ok_def and
    word_simpProof gc_fun_const_ok_def (GC_FUNCTION_PREDICATE_REFERENCES), each
    with its one WordSemGcFun argument: they inherit exactly the existing reviewed
    alias slots and positive word width. This does not review predicate clauses
    or authorize an arbitrary higher-order predicate or alias. The
    position names are one-based (`argument_N`, `result_N`). It verifies both
    carrier slots are `HolFiniteMapExact`, contain identical canonical map
    types, and account for every such occurrence in the abbreviation.
    """
    if (hol_reference in GC_FUNCTION_PREDICATE_REFERENCES and module and root
            and gc_function_predicate_signature(declaration_source, decl_name)):
        if not words_bitvec:
            return ["gc predicate must inherit words_as_type_indexed_bitvec together with map slots"]
        if positions != ("argument_4", "result_3"):
            return ["gc predicate must inherit exactly argument_4/result_3"]
        if re.search(r"^\s*(?:variable|variables|include|omit)\b",
                     strip_lean_comments("\n".join(lines)), re.M):
            return ["gc predicate requires self-contained binders"]
        if reviewed_gc_function_alias(module, root) is None:
            return ["gc predicate requires the unique source-reviewed WordSemGcFun alias"]
        return []
    errors: list[str] = []
    if not positions:
        return ["fmap_as_finite_support_function requires named map positions"]
    if len(set(positions)) != len(positions):
        errors.append("fmap_as_finite_support_function has duplicate positions")
    parsed: dict[str, int] = {}
    for position in positions:
        match = re.fullmatch(r"(argument|result)_([1-9][0-9]*)", position)
        if match is None:
            errors.append(
                "fmap_as_finite_support_function positions must be one-based "
                "`argument_N` or `result_N` entries"
            )
            continue
        key = match.group(1)
        if key in parsed:
            errors.append(
                "fmap_as_finite_support_function requires exactly one argument "
                "position and one result position"
            )
        parsed[key] = int(match.group(2))
    if set(parsed) != {"argument", "result"}:
        errors.append(
            "fmap_as_finite_support_function requires both argument_N and result_N"
        )

    source = strip_lean_comments(declaration_source)
    module_source = strip_lean_comments("\n".join(lines))
    if re.search(
        r"^\s*(?:private\s+|protected\s+)?theorem\s+"
        r"holFmapAsFiniteSupportWitness\b",
        module_source, re.M,
    ) is None:
        errors.append(
            "fmap_as_finite_support_function requires same-module canonical "
            "holFmapAsFiniteSupportWitness"
        )
    alias_start = re.search(rf"\babbrev\s+{re.escape(decl_name)}\b", source)
    if alias_start is None:
        errors.append(
            "fmap_as_finite_support_function applies only to a type abbreviation"
        )
        return errors
    alias_source = source[alias_start.start():]
    assign = alias_source.find(":=")
    if assign < 0:
        errors.append("fmap_as_finite_support_function cannot find the alias body")
        return errors
    body = alias_source[assign + 2:].strip()
    arrow = _split_type_top_level(body, ("→", "->"))
    if len(arrow) != 2:
        errors.append(
            "fmap_as_finite_support_function requires exactly one top-level function arrow"
        )
        return errors
    argument_parts = _tuple_type_components(arrow[0])
    if argument_parts is None:
        errors.append("fmap_as_finite_support_function argument must be a product")
    result_text = _strip_outer_parens(arrow[1])
    option = re.match(r"Option\s+(.+)$", result_text, re.S)
    result_parts = _tuple_type_components(option.group(1)) if option else None
    if result_parts is None:
        errors.append(
            "fmap_as_finite_support_function result must be Option of a product"
        )

    selected: list[str] = []
    for side, components in (("argument", argument_parts), ("result", result_parts)):
        if components is None or side not in parsed:
            continue
        index = parsed[side] - 1
        if index >= len(components):
            errors.append(
                f"fmap_as_finite_support_function {side}_{index + 1} is outside "
                f"the {len(components)}-component product"
            )
            continue
        component = components[index]
        if "HolFiniteMapExact" not in component:
            errors.append(
                f"fmap_as_finite_support_function {side}_{index + 1} must use "
                "HolFiniteMapExact; raw function maps are ineligible"
            )
        selected.append(re.sub(r"\s+", "", component))
        for other_index, other in enumerate(components):
            if other_index != index and "HolFiniteMapExact" in other:
                errors.append(
                    "fmap_as_finite_support_function positions omit another "
                    f"HolFiniteMapExact at {side}_{other_index + 1}"
                )
    if selected and len(set(selected)) != 1:
        errors.append(
            "fmap_as_finite_support_function argument and result map carriers "
            "must have the same exact type"
        )
    if source.count("HolFiniteMapExact") != 2:
        errors.append(
            "fmap_as_finite_support_function must account for exactly two "
            "HolFiniteMapExact occurrences in the alias"
        )
    return errors


def _function_declaration_signature(source: str, decl_name: str, *, all_binders: bool = False):
    """Return explicit argument binder types and result type for a def/theorem."""
    declaration = re.search(
        rf"\b(?:def|theorem|lemma)\s+{re.escape(decl_name)}\b", source
    )
    if declaration is None:
        return None
    end = source.find(":=", declaration.end())
    if end < 0:
        return None
    header = source[declaration.end():end]
    groups: list[tuple[str, str]] = []
    result_start: int | None = None
    index = 0
    while index < len(header):
        char = header[index]
        if char.isspace():
            index += 1
            continue
        if char == ":":
            result_start = index + 1
            break
        if char in "({[":
            close = {"(": ")", "{": "}", "[": "]"}[char]
            depth = 1
            cursor = index + 1
            while cursor < len(header) and depth:
                if header[cursor] == char:
                    depth += 1
                elif header[cursor] == close:
                    depth -= 1
                cursor += 1
            if depth:
                return None
            inner = header[index + 1:cursor - 1].strip()
            if all_binders:
                groups.append((char, inner))
            elif char == "(":
                binder = _split_type_top_level(inner, (":",))
                if len(binder) == 2:
                    groups.append((binder[0], binder[1]))
            index = cursor
            continue
        return None
    if result_start is None:
        return None
    return groups, header[result_start:].strip()


def _same_module_heterogeneous_fmap_witness_errors(
    lines: list[str], decl_name: str,
    target_arguments: list[tuple[str, str]], input_position: int,
    result_position: int, result_component_count: int,
) -> list[str]:
    """Require an unconditional, same-input raw/canonical projection theorem."""
    expected = f"holFmapAsFiniteSupportHeterogeneousFunctionWitness_{decl_name}"
    module_source = strip_lean_comments("\n".join(lines))
    pattern = re.compile(
        rf"^\s*(?:private\s+|protected\s+)?(?:theorem|lemma)\s+"
        rf"{re.escape(expected)}\b(?P<statement>[\s\S]*?):=",
        re.M,
    )
    match = pattern.search(module_source)
    if match is None:
        return [
            "fmap_as_finite_support_heterogeneous_function requires same-module "
            f"projection theorem `{expected}`"
        ]
    statement = match.group("statement")
    errors: list[str] = []
    # A written header omits section variables that Lean inserts at elaboration
    # (including proof premises forced by `include`). Do not approximate Lean's
    # section-variable inference here. This narrow qualifier requires a module
    # with self-contained binders and no ambient variable/context commands.
    # Widths and NeZero instances remain supported as explicit header binders.
    if re.search(r"\b(?:variable|variables|include|omit)\b", module_source):
        errors.append(
            "heterogeneous finite-map projection witness requires self-contained "
            "binders in a module without ambient variable/include/omit commands"
        )
    signature = _function_declaration_signature(module_source, expected)
    if signature is None:
        errors.append(
            "heterogeneous finite-map projection witness must have a typed theorem signature"
        )
        witness_arguments: list[tuple[str, str]] = []
        proposition = ""
    else:
        witness_arguments, proposition = signature
        normalize = lambda text: re.sub(r"\s+", "", text)
        if [(name.strip(), normalize(type_)) for name, type_ in witness_arguments] != [
            (name.strip(), normalize(type_)) for name, type_ in target_arguments
        ]:
            errors.append(
                "heterogeneous finite-map projection witness must quantify exactly "
                "the tagged operation's explicit inputs"
            )
    # Implicit proof premises and instances are premises too. Compare every
    # binder against the operation, including its width/type parameters.
    target_full = _function_declaration_signature(module_source, decl_name, all_binders=True)
    witness_full = _function_declaration_signature(module_source, expected, all_binders=True)
    normalize_binders = lambda sig: [(kind, re.sub(r"\s+", "", text))
                                     for kind, text in sig[0]] if sig else None
    if (target_full is None or witness_full is None or
            normalize_binders(target_full) != normalize_binders(witness_full)):
        errors.append("heterogeneous finite-map projection witness must retain exactly "
                      "all operation binders, with no extra implicit premises or instances")
    if "↔" in proposition:
        errors.append(
            "heterogeneous finite-map projection witness must conclude an equality, not iff"
        )
    equality = _split_type_top_level(_strip_outer_parens(proposition), ("=",))
    if len(equality) != 2:
        errors.append(
            "heterogeneous finite-map projection witness must be an unconditional equality"
        )
    else:
        left, right = (part.strip() for part in equality)
        left_has = identifier_token_occurs(left, decl_name)
        right_has = identifier_token_occurs(right, decl_name)
        if left_has == right_has:
            errors.append(
                "heterogeneous finite-map projection witness must mention the tagged "
                "operation on exactly one equality side"
            )
        target_side, raw_side = (left, right) if left_has else (right, left)
        if not _target_is_postfix_option_mapped(target_side, decl_name):
            errors.append(
                "heterogeneous finite-map projection witness must apply `.map` to "
                "the tagged operation's Option result"
            )
        if not _option_map_projects_result_slot(
            target_side, decl_name, result_position, result_component_count
        ):
            errors.append(
                "heterogeneous finite-map projection witness must project exactly "
                "the selected result_N map slot and preserve the other tuple slots"
            )
        target_lookups = re.findall(r"\b([A-Za-z_][A-Za-z0-9_']*)\.lookup\b", target_side)
        raw_lookups = re.findall(r"\b([A-Za-z_][A-Za-z0-9_']*)\.lookup\b", raw_side)
        if "fun" not in target_side or len(target_lookups) != 1:
            errors.append(
                "heterogeneous finite-map projection witness must project exactly "
                "one returned map through `.lookup` in its Option.map function"
            )
        input_name = (
            target_arguments[input_position][0].strip()
            if input_position < len(target_arguments) else ""
        )
        if (len(raw_lookups) != 1 or not input_name
                or raw_lookups[0] != input_name):
            errors.append(
                "heterogeneous finite-map projection witness must use the tagged "
                "canonical input's `.lookup` on the raw counterpart side"
            )
        if not re.search(r"\blookup[A-Za-z0-9_']*\b", raw_side):
            errors.append(
                "heterogeneous finite-map projection witness must compare with an "
                "independent raw lookup operation"
            )
        names = [name.strip() for name, _type in target_arguments]
        if all(re.fullmatch(r"[A-Za-z_][A-Za-z0-9_']*", name) for name in names):
            target_call = re.compile(
                r"\b" + re.escape(decl_name) + r"\s+" +
                r"\s+".join(re.escape(name) for name in names) + r"\b"
            )
            canonical_side = _strip_outer_parens(target_side)
            canonical_call = _parenthesized_content(canonical_side, 0)
            if (canonical_call is None or
                    target_call.fullmatch(canonical_call[0].strip()) is None):
                errors.append(
                    "heterogeneous finite-map projection witness must apply the "
                    "tagged operation to its explicit inputs in declaration order"
                )
            raw_arguments = [
                f"{name}.lookup" if index == input_position else name
                for index, name in enumerate(names)
            ]
            raw_call = re.compile(
                r"\b(lookup[A-Za-z0-9_']*)\s+" +
                r"\s+".join(re.escape(name) for name in raw_arguments) + r"\b"
            )
            raw_match = raw_call.fullmatch(_strip_outer_parens(raw_side))
            if raw_match is None or raw_match.group(1) == decl_name:
                errors.append(
                    "heterogeneous finite-map projection witness must apply an "
                    "independent raw lookup to the same explicit inputs in order"
                )
        for name, _type in target_arguments:
            name = name.strip()
            if (not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_']*", name)
                    or not identifier_token_occurs(target_side, name)
                    or not identifier_token_occurs(raw_side, name)):
                errors.append(
                    "heterogeneous finite-map projection witness must compare both "
                    "routes on every explicit operation input"
                )
                break
    return errors


def fmap_as_finite_support_heterogeneous_function_errors(
    lines: list[str], declaration_source: str, decl_name: str,
    positions: tuple[str, ...],
) -> list[str]:
    """Validate a direct lookup function with distinct canonical input/output maps.

    Unlike the existing abbreviation-only function qualifier, this models a
    definition whose code-map input and callee-locals result are both finite
    maps but have different value types. The same-module projection theorem is
    required because the output map is nested in an optional product.
    """
    errors: list[str] = []
    if len(positions) != 2 or len(set(positions)) != 2:
        return [
            "fmap_as_finite_support_heterogeneous_function requires exactly "
            "one argument_N and one result_N position"
        ]
    parsed: dict[str, int] = {}
    for position in positions:
        match = re.fullmatch(r"(argument|result)_([1-9][0-9]*)", position)
        if match is None or match.group(1) in parsed:
            errors.append(
                "fmap_as_finite_support_heterogeneous_function positions must be "
                "one-based argument_N/result_N with one of each"
            )
            continue
        parsed[match.group(1)] = int(match.group(2))
    if set(parsed) != {"argument", "result"}:
        return errors + [
            "fmap_as_finite_support_heterogeneous_function requires both argument_N and result_N"
        ]

    source = strip_lean_comments(declaration_source)
    signature = _function_declaration_signature(source, decl_name)
    if signature is None:
        errors.append(
            "fmap_as_finite_support_heterogeneous_function applies only to a "
            "direct function definition with a typed result"
        )
        return errors
    arguments, result = signature
    arg_index = parsed["argument"] - 1
    if arg_index >= len(arguments):
        errors.append(
            f"fmap_as_finite_support_heterogeneous_function argument_{arg_index + 1} "
            f"is outside the {len(arguments)} explicit function binders"
        )
        argument_type = ""
    else:
        argument_type = arguments[arg_index][1]
        if not _is_top_level_hol_finite_map_type(argument_type):
            errors.append(
                f"fmap_as_finite_support_heterogeneous_function argument_{arg_index + 1} "
                "must itself be HolFiniteMapExact; raw and product-wrapped maps are ineligible"
            )

    result_text = _strip_outer_parens(result)
    option = re.match(r"Option\s+(.+)$", result_text, re.S)
    result_parts = _tuple_type_components(option.group(1)) if option else None
    result_index = parsed["result"] - 1
    if result_parts is None:
        errors.append(
            "fmap_as_finite_support_heterogeneous_function result must be Option of a product"
        )
        result_type = ""
    else:
        if result_index >= len(result_parts):
            errors.append(
                f"fmap_as_finite_support_heterogeneous_function result_{result_index + 1} "
                f"is outside the {len(result_parts)} result components"
            )
            result_type = ""
        else:
            result_type = result_parts[result_index]
            if not _is_top_level_hol_finite_map_type(result_type):
                errors.append(
                    f"fmap_as_finite_support_heterogeneous_function result_{result_index + 1} "
                    "must itself be HolFiniteMapExact; raw and product-wrapped maps are ineligible"
                )

    declaration = re.search(rf"\bdef\s+{re.escape(decl_name)}\b", source)
    signature_source = source[declaration.start():] if declaration else source
    signature_source = signature_source.split(":=", 1)[0]
    map_occurrences = len(re.findall(r"\bHolFiniteMapExact\b", signature_source))
    if map_occurrences != 2:
        errors.append(
            "fmap_as_finite_support_heterogeneous_function must account for exactly "
            "the two selected HolFiniteMapExact carriers"
        )
    normalize = lambda text: re.sub(r"\s+", "", text)
    if argument_type and result_type and normalize(argument_type) == normalize(result_type):
        errors.append(
            "heterogeneous function qualifier requires distinct input and result map types; "
            "use fmap_as_finite_support_function when they are identical"
        )
    errors.extend(
        _same_module_heterogeneous_fmap_witness_errors(
            lines, decl_name, arguments, arg_index, result_index,
            len(result_parts) if result_parts is not None else 0,
        )
    )
    return errors


def fmap_as_finite_support_existentials_errors(
    lines: list[str], module: str, declaration_text: str, decl_name: str,
    binders: tuple[str, ...],
) -> list[str]:
    """Validate named existential HolFiniteMapExact binders.

    This qualifier records only the representation of an existential HOL
    finite-map witness. The existential scope and use remain part of the
    tagged declaration and require source review.
    """
    errors: list[str] = []
    if not binders:
        return ["fmap_as_finite_support_existentials requires at least one binder"]
    if len(set(binders)) != len(binders):
        errors.append("fmap_as_finite_support_existentials has duplicate binders")
    for binder in binders:
        existential = re.compile(
            r"∃\s*\(?\s*" + re.escape(binder)
            + r"\s*:\s*HolFiniteMapExact\b"
        )
        if existential.search(declaration_text) is None:
            errors.append(
                "fmap_as_finite_support_existentials binder "
                f"`{binder}` must be an existential typed HolFiniteMapExact"
            )
            continue
        witness = f"holFmapAsFiniteSupportExistentialWitness_{decl_name}_{binder}"
        source = strip_lean_comments("\n".join(lines))
        pattern = re.compile(
            rf"^\s*(?:@\[[\s\S]*?\]\s*)?(?:private\s+|protected\s+)?"
            rf"(?:theorem|lemma)\s+{re.escape(witness)}\b"
            rf"(?P<statement>[\s\S]*?):=",
            re.M,
        )
        match = pattern.search(source)
        if match is None:
            errors.append(
                "fmap_as_finite_support_existentials requires same-module "
                f"canonical witness `{witness}` for binder `{binder}`"
            )
            continue
        statement = match.group("statement")
        colon = _last_top_level_colon(statement)
        binder_zone = statement[:colon] if colon >= 0 else ""
        conclusion = statement[colon + 1:] if colon >= 0 else ""
        has_roundtrip = (
            re.search(r"ofBroad\s*[\(.A-Za-z_]", conclusion) is not None
            and re.search(r"toBroad\s*(?:lookup)?\s*[\(.A-Za-z_]", conclusion) is not None
            and re.search(
                r"\.lookup\s*=\s*" + re.escape(binder) + r"\.lookup\b",
                conclusion,
            ) is not None
            and re.search(
                r"\.finiteSupport\s*=\s*" + re.escape(binder) + r"\.finiteSupport\b",
                conclusion,
            ) is not None
            and re.search(
                r"ofBroad[\s\S]*?toBroad\s+" + re.escape(binder)
                + r"\s*\)\s*=\s*" + re.escape(binder) + r"\b",
                conclusion,
            ) is not None
        )
        if (
            colon < 0
            or "HolFiniteMapExact" not in binder_zone
            or re.search(
                r"\([^():]*:\s*[^)]*(?:lookup|finiteSupport|toBroad|ofBroad)[^)]*\)",
                binder_zone,
            ) is not None
            or "lookup" not in conclusion
            or "finiteSupport" not in conclusion
            or _split_top_level(conclusion, ("\u2192", "->")) is not None
            or not has_roundtrip
        ):
            errors.append(
                "fmap_as_finite_support_existentials witness "
                f"`{witness}` must state the canonical lookup/finiteSupport "
                f"toBroad/ofBroad roundtrip for `{binder}`"
            )
    return errors


def fmap_as_finite_support_equalities_witness_name(decl_name: str, index: int) -> str:
    return f"holFmapAsFiniteSupportEqualityWitness_{decl_name}_{index}"


def _count_top_level_conjuncts(text: str) -> int:
    count = 1
    depth = 0
    index = 0
    while index < len(text):
        char = text[index]
        if char in "([{":
            depth += 1
        elif char in ")]}":
            depth = max(0, depth - 1)
        elif depth == 0 and text.startswith("\u2227", index):
            count += 1
            index += 1
        index += 1
    return count


def _statement_conclusion(text: str) -> str:
    """Statement conclusion of a declaration text, with body and premises removed."""
    body = text.split(":=", 1)[0]
    colon = _last_top_level_colon(body)
    conclusion = body[colon + 1:] if colon >= 0 else body
    rest = conclusion
    while True:
        split = _split_top_level(rest, ("\u2192", "->"))
        if split is None:
            return rest
        rest = split[1]


def _statements_of_declaration(source: str, name: str) -> list[str]:
    """Return each `theorem|lemma name ...` statement up to its body `:=`.

    The body separator is the first `:=` at parenthesis depth zero, so a
    `:=` appearing inside a `let` or other nested term in the statement does
    not truncate it.
    """
    results: list[str] = []
    for match in re.finditer(
        rf"(?:theorem|lemma)\s+{re.escape(name)}\b", source
    ):
        start = match.end()
        depth = 0
        end = -1
        i = start
        while i < len(source) - 1:
            char = source[i]
            if char in "([{":
                depth += 1
            elif char in ")]}":
                depth = max(0, depth - 1)
            elif char == ":" and source[i + 1] == "=" and depth == 0:
                end = i
                break
            i += 1
        if end != -1:
            results.append(source[start:end])
    return results


def _binder_types(binder_zone: str) -> list[str]:
    """Return the declared type text of each top-level binder.

    Recognizes round `(name : type)`, curly `{name : type}` and square
    `[name : type]` delimiters, with balanced nesting. Binders without a `:`
    (for example instance braces `{α}`) contribute no type text. This is a
    syntactic scan of the source slice, not full Lean elaboration: a binder
    whose declared type is a named `Prop` alias or a predicate application is
    returned verbatim as its source text and may not be recognized as a proof
    premise by `_is_proof_premise_type`.
    """
    types: list[str] = []
    closer = {"(": ")", "{": "}", "[": "]"}
    stack: list[str] = []
    start = -1
    for i, ch in enumerate(binder_zone):
        if ch in closer:
            if not stack:
                start = i + 1
            stack.append(ch)
        elif ch in (")", "}", "]"):
            if stack and closer[stack[-1]] == ch:
                stack.pop()
                if not stack and start >= 0:
                    inner = binder_zone[start:i]
                    colon = _last_top_level_colon(inner)
                    if colon >= 0:
                        types.append(inner[colon + 1:].strip())
                    start = -1
    return types


def _is_proof_premise_type(type_text: str) -> bool:
    """Heuristically decide whether a binder type textually looks like a proof.

    This is a SYNTACTIC heuristic over source text, not an elaborated
    `Meta.isProp` test. It flags the literals `False`/`True` and any type text
    containing an arrow, iff, negation or equality. Consequences the callers
    must document: it can MISS proof premises written as a named `Prop` alias or
    as a predicate application (e.g. `(h : myProp x)`), and it can OVER-match
    legitimate data-level function types such as `(f : \u03b1 \u2192 \u03b2)`.
    Therefore passing this check is not a proof that the witness is
    unconditional; manual source review of the witness remains mandatory.
    """
    text = type_text.strip()
    if text in {"False", "True"}:
        return True
    return any(op in text for op in ("\u2192", "->", "\u2194", "\u00ac", "="))


def _declaration_premise_errors(declaration_text: str) -> list[str]:
    """Reject arrow premises and proof-premise binders on a tagged declaration.

    The singular finite-map equality qualifier asserts that the tagged theorem
    is the unconditional HOL equality. `_statement_conclusion` strips arrow
    premises before checking the conclusion shape, so a weakened theorem such
    as `theorem t (h : x = y) : HolFiniteMapExact.empty = a` would otherwise
    pass. This scans the declaration's own signature (from the `theorem`/`lemma`
    keyword, ignoring the preceding `@[hol ...]` attribute) for both kinds of
    premise.

    Like the witness check this is a syntactic scan: a premise whose type is a
    named `Prop` alias or predicate application may be missed, and a legitimate
    data-level function binder such as `(f : \u03b1 \u2192 \u03b2)` may be
    over-matched. Passing it is not a proof of unconditionality; manual source
    review remains mandatory.
    """
    errors: list[str] = []
    keyword = re.search(r"\b(?:theorem|lemma)\b", declaration_text)
    signature = declaration_text[keyword.start():] if keyword else declaration_text
    body = signature.split(":=", 1)[0]
    colon = _last_top_level_colon(body)
    if colon < 0:
        return errors
    binder_zone = body[:colon]
    rest = body[colon + 1:]
    premises = 0
    while True:
        split = _split_top_level(rest, ("\u2192", "->"))
        if split is None:
            break
        premises += 1
        rest = split[1]
    if premises:
        errors.append(
            "fmap_as_finite_support_equality requires the tagged declaration to "
            "be unconditional; it introduces an arrow premise"
        )
    for type_text in _binder_types(binder_zone):
        if _is_proof_premise_type(type_text):
            errors.append(
                "fmap_as_finite_support_equality requires the tagged declaration "
                f"to be unconditional; binder `{type_text}` is a proof premise, "
                "not typed data"
            )
    return errors


def _has_lookup_equality_witness(
    lines: list[str], witness: str, forbidden: str,
    expected: tuple[str, str] | None = None,
    unconditional: bool = False,
) -> tuple[bool, str]:
    source = strip_lean_comments("\n".join(lines))
    statements = _statements_of_declaration(source, witness)
    if not statements:
        return (False, f"has no same-module checked witness `{witness}`")
    if _witness_has_ambient_context(source, witness):
        return (False, f"witness `{witness}` requires self-contained binders; "
                "active ambient variable/include/omit commands can introduce "
                "inherited proof premises")
    for statement in statements:
        if forbidden and identifier_token_occurs(statement, forbidden):
            return (
                False,
                f"witness `{witness}` mentions the tagged theorem `{forbidden}`; "
                "an ignored-proof (threaded-argument) witness is rejected",
            )
        colon = _last_top_level_colon(statement)
        conclusion = statement[colon + 1:] if colon >= 0 else statement
        segments: list[str] = []
        rest = conclusion
        while True:
            split = _split_top_level(rest, ("\u2192", "->"))
            if split is None:
                segments.append(rest)
                break
            segments.append(split[0])
            rest = split[1]
        premises, final = segments[:-1], segments[-1]
        binder_zone = statement[:colon] if colon >= 0 else ""
        if unconditional:
            if premises:
                return (
                    False,
                    f"witness `{witness}` must be unconditional; it introduces "
                    "an arrow premise",
                )
            for type_text in _binder_types(binder_zone):
                if _is_proof_premise_type(type_text):
                    return (
                        False,
                        f"witness `{witness}` must be unconditional; binder "
                        f"`{type_text}` is a proof premise, not typed data",
                    )
        if re.search(r"(?i)\b(?:lookup|flookup)\b", binder_zone) and (
            "=" in binder_zone or "\u2194" in binder_zone
        ):
            return (
                False,
                f"witness `{witness}` assumes the target relation in a premise "
                "instead of proving it",
            )
        if _split_top_level(final, ("\u2194",)) is not None:
            return (
                False,
                f"witness `{witness}` must state an equality, not an iff",
            )
        relation = _split_top_level(final, ("=",))
        if relation is None:
            return (
                False,
                f"witness `{witness}` is vacuous: no equality conclusion",
            )
        lhs, rhs = relation
        if "".join(lhs.split()) == "".join(rhs.split()):
            return (
                False,
                f"witness `{witness}` is a self-equality; it does not "
                "establish lookup-level correspondence",
            )
        if not (
            re.search(r"(?i)\b(?:lookup|flookup)\b", lhs)
            and re.search(r"(?i)\b(?:lookup|flookup)\b", rhs)
        ):
            return (
                False,
                f"witness `{witness}` must apply a lookup on BOTH sides of its "
                "equality",
            )
        left_key = _lookup_key(lhs)
        right_key = _lookup_key(rhs)
        if left_key is None or right_key is None or left_key != right_key:
            return (
                False,
                f"witness `{witness}` must apply both lookups at the SAME key",
            )
        if expected is not None:
            expected_lhs = _normalize_whitespace(_strip_outer_parens(expected[0]))
            expected_rhs = _normalize_whitespace(_strip_outer_parens(expected[1]))
            left = _lookup_receiver_and_key(lhs)
            right = _lookup_receiver_and_key(rhs)
            if left is None or right is None:
                return (
                    False,
                    f"witness `{witness}` must state each equality side precisely "
                    "as `<map expression>.lookup <key>` (no wrapping `let`, "
                    "prefix lookup, or nested term)",
                )
            left_receiver = _normalize_whitespace(_strip_outer_parens(left[0]))
            right_receiver = _normalize_whitespace(_strip_outer_parens(right[0]))
            if {left_receiver, right_receiver} != {expected_lhs, expected_rhs}:
                return (
                    False,
                    f"witness `{witness}` is not associated with its numbered "
                    "finite-map equality conjunct",
                )
            if left[1] != right[1]:
                return (
                    False,
                    f"witness `{witness}` must apply both lookups at the SAME key",
                )
            if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_']*", left[1]):
                return (
                    False,
                    f"witness `{witness}` must bind its lookup key universally "
                    "(a fixed key does not establish the map equality)",
                )
            if not re.search(
                r"[\(\{]\s*" + re.escape(left[1]) + r"\s*[:\),\}]", binder_zone
            ):
                return (
                    False,
                    f"witness `{witness}` must bind its lookup key universally "
                    f"(no binder for `{left[1]}` in the statement)",
                )
        for premise in premises:
            if re.search(r"(?i)\b(?:lookup|flookup)\b", premise) and (
                "=" in premise or "\u2194" in premise
            ):
                return (
                    False,
                    f"witness `{witness}` assumes the target relation in a "
                    "premise instead of proving it",
                )
    return (True, "")


def fmap_as_finite_support_equalities_errors(
    lines: list[str], module: str,
    declaration_text: str, decl_name: str,
) -> list[str]:
    """Validate a theorem whose conclusion is a conjunction of finite-map equalities.

    HOL theorems such as `slc_tlc_rw` conclude several `|->` map equalities.
    Each conjunct must be witnessed at the lookup level by a same-module checked
    `holFmapAsFiniteSupportEqualityWitness_<decl>_<index>`; the witnesses must not
    mention the tagged theorem, so the ignored-proof/threaded-argument pattern is
    rejected. The tagged declaration's own statement must use the approved
    `HolFiniteMapExact` translation.

    This is a conjunction-specific qualifier, so at least two top-level equality
    conjuncts are required. The checks are syntactic: the checker enforces witness
    count, naming, exact `<map expression>.lookup <key>` equality shape, same-key
    application, a universally bound key, and per-conjunct textual association
    (each side must be exactly the corresponding conjunct side), but it does NOT
    prove that the Lean witnesses and conjuncts correspond to the HOL map
    equalities. Source review must compare each numbered witness against the HOL
    equality and record that comparison in the reviewer note.
    """
    errors: list[str] = []
    if "HolFiniteMapExact" not in declaration_text:
        errors.append(
            "fmap_as_finite_support_equalities requires the tagged declaration's "
            "conclusion to use the approved HolFiniteMapExact translation; a raw "
            "`\u03b1 \u2192 Option \u03b2` function map is ineligible"
        )
    conclusion = _statement_conclusion(declaration_text)
    count = _count_top_level_conjuncts(conclusion)
    if count < 2:
        errors.append(
            "fmap_as_finite_support_equalities requires at least two finite-map "
            "equality conjuncts in the tagged declaration's conclusion"
        )
        return errors
    conjuncts = _split_top_level_all(conclusion, "\u2227")
    for index in range(1, count + 1):
        witness = fmap_as_finite_support_equalities_witness_name(decl_name, index)
        conjunct = conjuncts[index - 1] if index - 1 < len(conjuncts) else ""
        expected = _split_top_level(_strip_outer_parens(conjunct), ("=",))
        if expected is None:
            errors.append(
                f"fmap_as_finite_support_equalities conjunct {index} is not a "
                "map equality"
            )
            continue
        ok, message = _has_lookup_equality_witness(
            lines, witness, decl_name, expected,
        )
        if not ok:
            errors.append(
                f"fmap_as_finite_support_equalities conjunct {index} {message}"
            )
    return errors


def fmap_as_finite_support_equality_witness_name(decl_name: str) -> str:
    return f"holFmapAsFiniteSupportEqualityWitness_{decl_name}"


def fmap_as_finite_support_equality_errors(
    lines: list[str], module: str,
    declaration_text: str, decl_name: str,
) -> list[str]:
    """Validate a theorem whose conclusion is a SINGLE finite-map equality.

    HOL theorems such as `res_var_FEMPTY` conclude exactly one `|->` map
    equality.  The tagged declaration must conclude exactly one whole
    `HolFiniteMapExact` equality, with no conjunction, no iff, and no premise
    (an arrow premise or proof-premise binder on the tagged declaration is
    rejected), and its two sides must be witnessed at the lookup level by a
    same-module checked, unconditional
    `holFmapAsFiniteSupportEqualityWitness_<decl>`: an equality
    `<side>.lookup k = <side>.lookup k` at one universally bound key, with the
    two receivers exactly the tagged conclusion's two sides.  The witness must
    not mention the tagged theorem in its statement/header (rejecting the
    ignored-proof / threaded-argument pattern), but its proof body may reuse the
    tagged theorem's established proof; it must not be a self-equality.

    The checks are syntactic: they validate shape, naming, same-key
    application, a universally bound key, and side association, but they do NOT
    prove that the Lean witness corresponds to the HOL map equality.  Source
    review must compare the witness against the HOL equality.  Premise and
    unconditional-binder rejection is likewise syntactic: `_binder_types`
    recognizes `(...)`, `{...}` and `[...]` delimiters, and
    `_is_proof_premise_type` flags only literal `False`/`True` and type text
    containing an arrow, iff, negation or equality.  It can therefore MISS a
    proof premise written as a named `Prop` alias or predicate application, and
    can OVER-match a legitimate data-level function binder.  Passing this gate
    is not a proof of unconditionality; manual review is mandatory.
    """
    errors: list[str] = []
    if "HolFiniteMapExact" not in declaration_text:
        errors.append(
            "fmap_as_finite_support_equality requires the tagged declaration's "
            "conclusion to use the approved HolFiniteMapExact translation; a raw "
            "`\u03b1 \u2192 Option \u03b2` function map is ineligible"
        )
    errors.extend(_declaration_premise_errors(declaration_text))
    conclusion = _statement_conclusion(declaration_text)
    if _split_top_level(conclusion, ("\u2194",)) is not None:
        errors.append(
            "fmap_as_finite_support_equality requires a single map equality, "
            "not an iff"
        )
        return errors
    count = _count_top_level_conjuncts(conclusion)
    if count != 1:
        errors.append(
            "fmap_as_finite_support_equality requires exactly one finite-map "
            "equality in the tagged declaration's conclusion (use "
            "fmap_as_finite_support_equalities for a conjunction)"
        )
        return errors
    expected = _split_top_level(_strip_outer_parens(conclusion), ("=",))
    if expected is None:
        errors.append(
            "fmap_as_finite_support_equality conclusion is not a map equality"
        )
        return errors
    kind = re.search(
        r"\b(theorem|lemma|example|def|abbrev|opaque|instance|structure|inductive)\b",
        declaration_text,
    )
    if kind is not None and kind.group(1) not in {"theorem", "lemma"}:
        errors.append(
            "fmap_as_finite_support_equality may tag only a theorem or lemma; "
            f"found `{kind.group(1)}`"
        )
    witness = fmap_as_finite_support_equality_witness_name(decl_name)
    ok, message = _has_lookup_equality_witness(
        lines, witness, decl_name, expected, unconditional=True,
    )
    if not ok:
        errors.append(f"fmap_as_finite_support_equality {message}")
    return errors


def has_list_array_witness(lines: list[str], field: str) -> bool:
    """Require a same-module, kernel-checked representation theorem for a field.

    The witness convention is `holListArrayWitness_<field>` and its theorem
    type must mention both `RepresentsHOLNodeList` and the qualified state field.
    The relation must occur in the result type, exactly once, and not in any
    premise: a theorem assuming the relation it claims to establish is not a
    representation witness. Lake checks the witness proof when it builds the
    tagged module; this syntactic gate does not itself prove semantic
    correspondence.
    """
    source = strip_lean_comments("\n".join(lines))
    pattern = re.compile(
        rf"^\s*(?:@[\s\S]*?\]\s*)?(?:private\s+|protected\s+)?"
        rf"(?:theorem|lemma)\s+holListArrayWitness_{re.escape(field)}\b"
        rf"(?P<type>[\s\S]*?):=",
        re.M,
    )
    for match in pattern.finditer(source):
        statement = match.group("type")
        depth = 0
        result_start: int | None = None
        for index, char in enumerate(statement):
            if char in "([{":
                depth += 1
            elif char in ")]}":
                depth -= 1
            elif char == ":" and depth == 0:
                result_start = index + 1
        if result_start is None:
            continue
        premises, result_type = statement[:result_start], statement[result_start:]
        if (
            "RepresentsHOLNodeList" not in premises
            and result_type.count("RepresentsHOLNodeList") == 1
            and re.search(rf"\.\s*{re.escape(field)}\b", result_type)
        ):
            return True
    return False


def list_as_array_errors(lines: list[str], fields: tuple[str, ...], module: str) -> list[str]:
    """Validate qualified fields against local state declarations and witnesses."""
    errors: list[str] = []
    declared_fields = structure_fields(lines)
    for field in fields:
        if field not in declared_fields:
            errors.append(
                f"list_as_array field `{field}` is not a field of a Lean structure "
                f"declared in {module}"
            )
        if not has_list_array_witness(lines, field):
            errors.append(
                f"list_as_array field `{field}` has no same-module checked witness "
                f"`holListArrayWitness_{field}`"
            )
    return errors


def has_mlstring_witness(lines: list[str], declaration: str) -> bool:
    """Require a same-module byte-range theorem for a byte-observable tag.

    The theorem is named for the tagged declaration and its result must
    establish `NameRanged`. Input range premises are allowed. This syntax check
    does not establish that the result is the right output or that a premise is
    discharged on the executed path; Lean checks the proof and source review
    records those obligations.
    """
    source = strip_lean_comments("\n".join(lines))
    pattern = re.compile(
        rf"^\s*(?:@\[[\s\S]*?\]\s*)?(?:private\s+|protected\s+)?"
        rf"(?:theorem|lemma)\s+holMlStringWitness_{re.escape(declaration)}\b"
        rf"(?P<type>[\s\S]*?):=",
        re.M,
    )
    for match in pattern.finditer(source):
        statement = match.group("type")
        depth = 0
        result_start: int | None = None
        for index, char in enumerate(statement):
            if char in "([{":
                depth += 1
            elif char in ")]}":
                depth -= 1
            elif char == ":" and depth == 0:
                result_start = index + 1
        if result_start is None:
            continue
        result_type = statement[result_start:]
        result = result_type.strip()
        if re.match(r"^(?:[A-Za-z0-9_]+\.)*NameRanged\b", result):
            return True
    return False


def names_as_string_errors(
    lines: list[str],
    identifiers: tuple[str, ...],
    boundary_identifiers: tuple[str, ...],
    module: str,
    declaration: str,
) -> list[str]:
    """Validate reviewed HOL `mlstring` identifiers and byte boundaries."""
    errors: list[str] = []
    if len(set(identifiers)) != len(identifiers):
        errors.append("names_as_string identifiers must be distinct")
    if len(set(boundary_identifiers)) != len(boundary_identifiers):
        errors.append("names_as_string_boundary identifiers must be distinct")
    for identifier in boundary_identifiers:
        if identifier not in identifiers:
            errors.append(
                f"names_as_string_boundary identifier `{identifier}` is not listed by "
                "names_as_string"
            )
        if not has_mlstring_witness(lines, declaration):
            errors.append(
                f"names_as_string_boundary identifier `{identifier}` in {module}:{declaration} "
                f"has no same-module checked witness `holMlStringWitness_{declaration}` "
                "with a NameRanged result"
            )
    return errors


_DIMENSION_IDENT_RE = re.compile(r"[A-Za-z_][A-Za-z0-9_']*")
_DIMENSION_DIGITS_RE = re.compile(r"[0-9]+")
_DIMENSION_DIGITS_PAREN_RE = re.compile(r"[0-9]+")


def word_dimension_atoms(text: str) -> list[tuple[str, bool]]:
    """Structurally read the dimension argument of every word-carrier use.

    Rather than a partial regex over bare ``BitVec <id>`` / ``BitVec <digits>``
    spellings, this scans each word carrier (``BitVec`` or a reviewed
    abbreviation) and consumes the actual following dimension atom, so parenthesised
    and arithmetic forms are seen instead of silently skipped. Returns
    ``(atom, parenthesised)`` pairs where ``atom`` is the unparenthesised text of
    the dimension argument; a carrier with no readable argument is skipped.
    """
    atoms: list[tuple[str, bool]] = []
    for match in WORD_CARRIER_TOKEN_RE.finditer(text):
        pos = match.end()
        while pos < len(text) and text[pos].isspace():
            pos += 1
        if pos >= len(text):
            continue
        char = text[pos]
        if char == "(":
            depth = 0
            start = pos
            while pos < len(text):
                if text[pos] == "(":
                    depth += 1
                elif text[pos] == ")":
                    depth -= 1
                    if depth == 0:
                        pos += 1
                        break
                pos += 1
            atoms.append((text[start + 1:pos - 1].strip(), True))
        elif char.isdigit():
            start = pos
            while pos < len(text) and text[pos].isdigit():
                pos += 1
            atoms.append((text[start:pos], False))
        elif char.isalpha() or char == "_":
            start = pos
            while pos < len(text) and (text[pos].isalnum() or text[pos] in "_'"):
                pos += 1
            atoms.append((text[start:pos], False))
    return atoms


def word_dimension_identifier_atoms(text: str) -> list[str]:
    """The identifier word dimensions in `text` (parenthesised or bare)."""
    identifiers: list[str] = []
    for atom, parenthesised in word_dimension_atoms(text):
        if parenthesised:
            if _DIMENSION_IDENT_RE.fullmatch(atom) and not atom[0].isdigit():
                identifiers.append(atom)
        elif _DIMENSION_IDENT_RE.fullmatch(atom):
            identifiers.append(atom)
    return identifiers


def word_dimension_errors(text: str) -> list[str]:
    """Reject every nonpositive or unconstrained word dimension in `text`.

    Inspects every word dimension structurally: an identifier dimension must be a
    bound ``Nat`` parameter with its own ``[NeZero <width>]`` discharge; a numeric
    dimension (including leading-zero and parenthesised spellings such as ``00``,
    ``(0)``) must be positive; and a parenthesised or arithmetic dimension that is
    neither a plain identifier nor plain digits (``(width - width)``, ``(0 + 0)``)
    is rejected rather than skipped.
    """
    errors: list[str] = []
    for atom, parenthesised in word_dimension_atoms(text):
        inner = atom
        if parenthesised and _DIMENSION_DIGITS_RE.fullmatch(inner):
            spelling = f"BitVec ({inner})"
        elif _DIMENSION_DIGITS_RE.fullmatch(inner):
            spelling = f"BitVec {inner}"
        elif parenthesised and _DIMENSION_IDENT_RE.fullmatch(inner) and not inner[0].isdigit():
            spelling = f"BitVec ({inner})"
        elif not parenthesised and _DIMENSION_IDENT_RE.fullmatch(inner):
            spelling = f"BitVec {inner}"
        else:
            errors.append(
                f"`BitVec ({inner})` is not a positive width identifier; every word "
                "dimension in scope must be an explicit `Nat` parameter with its own "
                "`[NeZero <width>]` discharge"
            )
            continue
        if _DIMENSION_DIGITS_RE.fullmatch(inner):
            if int(inner) == 0:
                errors.append(
                    f"`{spelling}` is not a positive width; the qualifier records HOL's "
                    "positive `dimindex (:α)` dimension"
                )
            continue
        width = inner
        if NAT_WIDTH_BINDER_RE.search(text) is None or re.search(
            r"[\{\(]\s*" + re.escape(width) + r"\s*:\s*Nat\s*[\}\)]", text
        ) is None:
            errors.append(
                f"`{spelling}` is not at a `Nat` width binder; every word "
                "dimension in scope must be an explicit positive-width parameter"
            )
        elif re.search(
            r"\[\s*NeZero\s+" + re.escape(width) + r"\s*\]", text
        ) is None:
            errors.append(
                f"`{spelling}` lacks its own `[NeZero {width}]` discharge; "
                "every word dimension in scope must be constrained"
            )
    for neZero in re.finditer(r"\[\s*NeZero\s+([^\]]*?)\s*\]", text):
        argument = neZero.group(1).strip()
        if re.fullmatch(r"\(?\s*[A-Za-z_][A-Za-z0-9_']*\s*\)?", argument):
            continue
        if re.fullmatch(r"\(?\s*0+\s*\)?", argument):
            errors.append(
                "`[NeZero 0]` is not a valid positivity discharge; the dimension must "
                "be a positive width identifier"
            )
        else:
            errors.append(
                f"`[NeZero {argument}]` must discharge a width identifier; a literal "
                "or compound dimension is not a valid positivity discharge"
            )
    return errors


def reviewed_hol_prog_word_alias(signature: str, module: str, root: str) -> bool:
    """Resolve the one reviewed shared-word StackLang alias, never by name alone.

    HolProg is an instantiation of the generic seven-payload Prog, not a fresh
    carrier owner. Check its exact RHS, positive binder, import reachability,
    unique alias name and each word-bearing payload's actual owning declaration.
    This is intentionally not arbitrary abbreviation unfolding.
    """
    occurrences = re.findall(
        r"\b((?:[A-Za-z_][A-Za-z0-9_']*\.)*HolProg)\s+([A-Za-z_][A-Za-z0-9_']*)\b",
        signature,
    )
    if any(name not in ("HolProg", "StackLang.HolProg", "Compiler.Backend.StackLang.HolProg",
                        "Flapjack.Compiler.Backend.StackLang.HolProg")
           for name, _ in occurrences):
        return False
    uses = [width for _, width in occurrences]
    if not uses or any(
        not re.search(r"[({]\s*" + re.escape(w) + r"\s*:\s*Nat\s*[)}]", signature)
        or not re.search(r"\[\s*NeZero\s+" + re.escape(w) + r"\s*\]", signature)
        for w in uses
    ):
        return False
    return _hol_prog_alias_module_ok(module, root)


def _carrier_declaration_starts(info: _LeanFileInfo, carrier: str) -> list[int]:
    """Offsets of every comment-free declaration of `carrier` in one file."""
    return info.parsed(
        f"carrier_declaration_starts:{carrier}",
        lambda i: [
            match.start() for match in re.finditer(
                r"^\s*(?:abbrev|def|opaque|structure|inductive)\s+"
                r"(?:[A-Za-z_][A-Za-z0-9_']*\.)*" + re.escape(carrier) + r"\b",
                strip_lean_comments(i.text), re.M)
        ],
    )


@lru_cache(maxsize=None)
def _hol_prog_alias_module_ok(module: str, root: str) -> bool:
    """The module-dependent half of `reviewed_hol_prog_word_alias`.

    It reads only the import closure of `module`, never the signature, so one
    result serves every tagged declaration of the module in a checker run.
    """
    pending = [module]
    infos = {}
    while pending:
        name = pending.pop()
        if name in infos:
            continue
        info = _lean_file_info(module_source_file(name, root))
        if info is None:
            continue
        infos[name] = info
        pending.extend(info.imports)
    owner = "Flapjack.Compiler.Backend.StackLang.Prog"
    if owner not in infos:
        return False
    declarations = []
    for name, info in infos.items():
        text = strip_lean_comments(info.text)
        for start in _carrier_declaration_starts(info, "HolProg"):
            declarations.append((name, text[start:]))
    if len(declarations) != 1 or declarations[0][0] != owner:
        return False
    expected = """abbrev HolProg (width : Nat) [NeZero width] :=
      Flapjack.Compiler.Backend.StackLang.Prog (HolInst width) HolCmp (HolRegImm width)
        HolBinop HolMemop (HolAddr width) Flapjack.Basis.Pure.MlString.MlString"""
    if not any(site[1:3] == ("cakeml/compiler/backend/stackLangScript.sml", "prog")
               for site in hol_attribute_sites(infos[owner].lines)):
        return False
    actual = re.split(r"\n\s*end\b", declarations[0][1], maxsplit=1)[0]
    if " ".join(actual.split()) != " ".join(expected.split()):
        return False
    asm = "Flapjack.Compiler.Encoders.Asm"
    if asm not in infos:
        return False
    owners = imported_inductive_owners(module, root)
    for payload in ("HolInst", "HolRegImm", "HolAddr"):
        payload_declarations = [name for name, info in infos.items()
            for _ in _carrier_declaration_starts(info, payload)]
        if payload_declarations != [asm]:
            return False
        candidates = owners.get(payload, [])
        if len(candidates) != 1 or candidates[0][0] != asm:
            return False
        _, header, fields = candidates[0]
        if not re.search(r"\(width\s*:\s*Nat\)\s*\[NeZero\s+width\]", header):
            return False
        if not any(field_mentions_word_carrier(field, "width") for field in fields.values()):
            return False
        if word_dimension_errors(header + "\n" + "\n".join(fields.values())):
            return False
    return True


def source_bound_rounding_enum(root: Path) -> bool:
    """Only the literal, uniquely owned HOL rounding enum is real-free.

    This does not exempt its module or any rounding operation. Fail closed
    when either source carrier changes, or another Lean declaration shadows
    the reviewed name (including an abbrev/alias with that name).
    """
    owner = root / "Flapjack/Misc/BinaryIeeeRound.lean"
    original = root / "HOL/src/floating-point/binary_ieeeScript.sml"
    if not owner.is_file() or not original.is_file():
        return False
    lean = strip_lean_comments(owner.read_text(encoding="utf-8"))
    pattern = (r"(?m)^inductive HolRounding where\s*"
               r"\| roundTiesToEven\s*\| roundTowardPositive\s*"
               r"\| roundTowardNegative\s*\| roundTowardZero\s*"
               r"deriving DecidableEq, Repr\s*(?=/--|def |noncomputable |$)")
    carrier = re.search(pattern, lean)
    if carrier is None:
        return False
    scopes = re.findall(r"(?m)^(?:namespace|end)\b[^\n]*", lean[:carrier.start()])
    if scopes != ["namespace Flapjack"]:
        return False
    # HOL comments nest: a stale enum quoted in a comment is not its owner.
    raw = original.read_text(encoding="utf-8")
    kept, depth, i = [], 0, 0
    while i < len(raw):
        if raw.startswith("(*", i):
            depth += 1
            i += 2
        elif depth and raw.startswith("*)", i):
            depth -= 1
            i += 2
        else:
            if not depth:
                kept.append(raw[i])
            i += 1
    if depth:
        return False
    hol = "".join(kept)
    if not re.search(r"Datatype:\s*rounding\s*=\s*roundTiesToEven\s*"
                     r"\| roundTowardPositive\s*\| roundTowardNegative\s*"
                     r"\| roundTowardZero\s*End\b", hol):
        return False
    owners = []
    for path in root.glob("Flapjack/**/*.lean"):
        text = strip_lean_comments(path.read_text(encoding="utf-8"))
        owners.extend(path for match in REALS_RENDERING_DECL_RE.finditer(text)
                      if match.group(1).rsplit(".", 1)[-1] == "HolRounding")
    return owners == [owner]


